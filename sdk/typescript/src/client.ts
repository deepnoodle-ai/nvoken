  async invoke<TOutput extends object = JsonObject>(
    request: InvokeRequest<TOutput>,
    signal?: AbortSignal,
  ): Promise<InvocationHandle<TOutput>> {
    if (!request.agentKey || !validInvokeInput(request.input)) {
      throw new NvokenError("validation", "agentKey and input are required");
    }
    if (request.sessionId && request.sessionKey) {
      throw new NvokenError(
        "validation",
        "sessionId and sessionKey are mutually exclusive",
      );
    }
    if (request.ifActive !== undefined
      && request.ifActive !== "reject"
      && request.ifActive !== "supersede"
      && request.ifActive !== "interrupt") {
      throw new NvokenError(
        "validation",
        "ifActive must be reject, supersede, or interrupt",
      );
    }
    if (request.onBudgetExhausted !== undefined
      && request.onBudgetExhausted !== "stop"
      && request.onBudgetExhausted !== "pause") {
      throw new NvokenError(
        "validation",
        "onBudgetExhausted must be stop or pause",
      );
    }
    if (request.definitionId !== undefined) {
      if (!request.definitionId) {
        throw new NvokenError("validation", "definitionId cannot be empty");
      }
    } else {
      validateModel(request.model);
    }
    if (
      request.instructions !== undefined
      && !request.instructions.trim()
    ) {
      throw new NvokenError("validation", "instructions cannot be blank");
    }
    const idempotencyKey = request.idempotencyKey ?? `nvoken-${globalThis.crypto.randomUUID()}`;
    const generatedRequest = invocationRequestToWire(request, idempotencyKey);
    const ack = await this.replaySafe(
      () => this.invocations.createInvocation(
        { createInvocationRequest: generatedRequest },
        { signal },
      ),
      signal,
    );
    return new InvocationHandle<TOutput>(
      this,
      ack.id,
      idempotencyKey,
      ack.sessionId,
      ack.agentId,
      ack.status,
      ack.deduplicated,
      ack.deadlineAt,
      request.model?.provider,
    );
  }

